@pytest.mark.asyncio
async def test_scan_dependencies_nuget_and_pub():
    with tempfile.TemporaryDirectory() as tmpdir:
        # Create a csproj file
        csproj_path = os.path.join(tmpdir, "App.csproj")
        with open(csproj_path, "w") as f:
            f.write("""<Project Sdk="Microsoft.NET.Sdk">
  <ItemGroup>
    <PackageReference Include="Newtonsoft.Json" Version="12.0.2" />
  </ItemGroup>
</Project>
""")
        # Create a pubspec.lock file
        pubspec_path = os.path.join(tmpdir, "pubspec.lock")
        with open(pubspec_path, "w") as f:
            f.write("""packages:
  http:
    dependency: "direct main"
    source: hosted
    version: "0.13.0"
""")

        mock_nuget_vuln = DepVulnerability(
            package="Newtonsoft.Json",
            version="12.0.2",
            cve_id="GHSA-5crp-9r3c-p9vr",
            severity=Severity.HIGH.value,
            cvss_score=7.5,
            description="Improper Handling of Exceptional Conditions in Newtonsoft.Json",
            fix_version="13.0.1",
        )
        mock_pub_vuln = DepVulnerability(
            package="http",
            version="0.13.0",
            cve_id="GHSA-pub-1234",
            severity=Severity.MEDIUM.value,
            cvss_score=5.0,
            description="Vulnerability in http package",
            fix_version="0.13.3",
        )

        async def fake_query_osv(package, version, ecosystem):
            if ecosystem == "NuGet" and package == "Newtonsoft.Json":
                return [mock_nuget_vuln]
            elif ecosystem == "Pub" and package == "http":
                return [mock_pub_vuln]
            return []

        with patch("maunprekshak.scanner.deps._query_osv", side_effect=fake_query_osv):
            findings = await scan_dependencies(tmpdir)

        cve_ids = [f.cve_id for f in findings]
        assert "GHSA-5crp-9r3c-p9vr" in cve_ids
        assert "GHSA-pub-1234" in cve_ids
