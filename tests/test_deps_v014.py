def test_parse_pubspec_yaml():
    pubspec_content = """name: my_flutter_app
description: A new Flutter project.
environment:
  sdk: ">=2.12.0 <3.0.0"

dependencies:
  flutter:
    sdk: flutter
  http: ^0.13.3
  path: 1.8.0
  shared_preferences:
    version: ^2.0.6

dev_dependencies:
  flutter_test:
    sdk: flutter
  pedantic: ^1.10.0
"""
    with tempfile.NamedTemporaryFile("w", suffix=".yaml", delete=False) as f:
        f.write(pubspec_content)
        fname = f.name
    try:
        pkgs = dict(parse_pubspec_yaml(fname))
        assert "flutter" not in pkgs
        assert "flutter_test" not in pkgs
        assert pkgs.get("http") == "0.13.3"
        assert pkgs.get("path") == "1.8.0"
        assert pkgs.get("shared_preferences") == "2.0.6"
        assert pkgs.get("pedantic") == "1.10.0"
    finally:
        os.unlink(fname)


