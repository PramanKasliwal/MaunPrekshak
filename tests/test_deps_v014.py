def test_parse_csproj():
    csproj_content = """<Project Sdk="Microsoft.NET.Sdk">
  <ItemGroup>
    <PackageReference Include="Newtonsoft.Json" Version="13.0.1" />
    <PackageReference Include="Microsoft.Extensions.Logging">
      <Version>6.0.0</Version>
    </PackageReference>
  </ItemGroup>
</Project>
"""
    with tempfile.NamedTemporaryFile("w", suffix=".csproj", delete=False) as f:
        f.write(csproj_content)
        fname = f.name
    try:
        pkgs = dict(parse_csproj(fname))
        assert pkgs.get("Newtonsoft.Json") == "13.0.1"
        assert pkgs.get("Microsoft.Extensions.Logging") == "6.0.0"
    finally:
        os.unlink(fname)


